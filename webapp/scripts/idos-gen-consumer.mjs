// One-off: generate this app's idOS CONSUMER identity (its own keys, generated once).
//
// Produces two keypairs, matching what @idos-network/consumer expects (see the pay-demo
// reference examples/pay-demo/app/providers/idos.server.ts):
//   - a nacl SIGN keypair  -> the consumer auth signer (idOSConsumer consumerSigner).
//     The SDK derives the consumer's on-chain identity as hex(signPublicKey) via
//     implicitAddressFromPublicKey(bs58Encode(pk)), which is exactly Buffer(pk).toString("hex").
//     That hex string is the `consumerAuthPublicKey` the user grants access to.
//   - a nacl BOX keypair   -> the recipient encryption key. The enclave re-encrypts the
//     shared credential to base64(boxPublicKey); the server decrypts with base64(boxSecretKey).
//
// Secrets (IDOS_CONSUMER_SIGNER, IDOS_RECIPIENT_ENC_PRIVATE_KEY) are appended to
// webapp/.env.local (gitignored). Only the NON-secret public config is printed to stdout.
//
// Run once:  node scripts/idos-gen-consumer.mjs
import nacl from "tweetnacl";
import { readFileSync, appendFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const b64 = (u8) => Buffer.from(u8).toString("base64");
// UPPERCASE hex to match the SDK's implicitAddressFromPublicKey output (== idOSConsumer.address).
const hex = (u8) => Buffer.from(u8).toString("hex").toUpperCase();

const sign = nacl.sign.keyPair(); // ed25519 auth signer
const box = nacl.box.keyPair(); // x25519 encryption recipient

const secrets = {
  IDOS_CONSUMER_SIGNER: b64(sign.secretKey), // base64 nacl.sign secret (64 bytes)
  IDOS_RECIPIENT_ENC_PRIVATE_KEY: b64(box.secretKey), // base64 nacl.box secret (32 bytes)
};
const publics = {
  NEXT_PUBLIC_IDOS_CONSUMER_AUTH_PUBLIC_KEY: hex(sign.publicKey), // hex ed25519 pubkey = consumer.address
  NEXT_PUBLIC_IDOS_CONSUMER_ENCRYPTION_PUBLIC_KEY: b64(box.publicKey), // base64 box pubkey
  NEXT_PUBLIC_IDOS_NODE_URL: "https://nodes.playground.idos.network",
  NEXT_PUBLIC_IDOS_ENCLAVE_URL: "https://enclave.playground.idos.network/",
  IDOS_NODE_URL: "https://nodes.playground.idos.network",
};

const envPath = join(dirname(fileURLToPath(import.meta.url)), "..", ".env.local");
const already = existsSync(envPath) && readFileSync(envPath, "utf8").includes("IDOS_CONSUMER_SIGNER=");
if (already) {
  console.error("Refusing to overwrite: IDOS_CONSUMER_SIGNER already present in .env.local. Delete those lines to regenerate.");
  process.exit(1);
}

const block =
  "\n# idOS consumer identity (generated by scripts/idos-gen-consumer.mjs). Secrets — never commit.\n" +
  Object.entries(secrets).map(([k, v]) => `${k}=${v}`).join("\n") + "\n" +
  Object.entries(publics).map(([k, v]) => `${k}=${v}`).join("\n") + "\n";
appendFileSync(envPath, block);

// Only public values to stdout; secrets went to .env.local.
console.log("Wrote idOS consumer keys to .env.local. Public (non-secret) config:");
for (const [k, v] of Object.entries(publics)) console.log(`${k}=${v}`);
